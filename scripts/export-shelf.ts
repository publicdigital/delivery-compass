/**
 * Export the numbers behind the public /trial page's corpus visual.
 *
 * /trial is public and everything under /assets/data sits behind the password, so the
 * page needs its own small, dated copy: per source, its word count, sections, extracted
 * obligations and page dates, plus the curated relations. Word counts come from the
 * database rather than the exported JSON because the export caps long sections.
 *
 * This is a one-off snapshot, not part of `refresh`: the page's prose quotes some of
 * these figures, so regenerating it means re-reading the page too.
 *
 * Run: node --experimental-strip-types scripts/export-shelf.ts
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { openDb } from "../pipeline/db.ts";

const DATA = new URL("../assets/data/", import.meta.url);
const OUT = fileURLToPath(new URL("../trial/shelf-data.js", import.meta.url));
const read = (f: string) => JSON.parse(readFileSync(new URL(f, DATA), "utf8"));

const sources = read("sources.json") as Record<string, any>[];
const relations = read("relations.json") as Record<string, any>[];
const meta = read("meta.json");

const db = openDb();
const words = new Map<string, number>();
const sections = new Map<string, number>();
const pages = new Map<string, Set<string>>();
const latest = new Map<string, string>();
type SectionRow = { source_id: string; doc_path: string; text: string; doc_updated_at: string | null };
for (const row of db.prepare("SELECT source_id, doc_path, text, doc_updated_at FROM sections").iterate() as unknown as Iterable<SectionRow>) {
  const id = row.source_id;
  words.set(id, (words.get(id) ?? 0) + row.text.split(/\s+/).filter(Boolean).length);
  sections.set(id, (sections.get(id) ?? 0) + 1);
  if (!pages.has(id)) pages.set(id, new Set());
  pages.get(id)!.add(row.doc_path.split("#")[0] ?? row.doc_path);
  const d = row.doc_updated_at?.slice(0, 10);
  if (d && d > (latest.get(id) ?? "")) latest.set(id, d);
}
const must = new Map<string, number>();
const statements = new Map<string, number>();
const strength: Record<string, number> = {};
for (const row of db.prepare("SELECT source_id, strength, count(*) AS n FROM obligations GROUP BY 1, 2").all() as Record<string, any>[]) {
  statements.set(row.source_id, (statements.get(row.source_id) ?? 0) + row.n);
  if (row.strength === "mandatory") must.set(row.source_id, row.n);
  strength[row.strength] = (strength[row.strength] ?? 0) + row.n;
}

const shelf = {
  indexedAt: meta.indexedAt,
  strength,
  sources: sources.map((s) => ({
    id: s.id, t: s.title, b: s.body, sp: s.spine, au: s.authority, st: s.contentStatus, url: s.url,
    w: words.get(s.id) ?? 0, s: sections.get(s.id) ?? 0, p: pages.get(s.id)?.size ?? 0,
    m: must.get(s.id) ?? 0, o: statements.get(s.id) ?? 0, d1: latest.get(s.id) ?? null,
    wd: s.withdrawnOn, why: s.notIndexedReason,
  })),
  rel: relations.map((r) => ({ f: r.from, t: r.to, ty: r.type })),
};

writeFileSync(OUT, `// Generated by scripts/export-shelf.ts from the index of ${meta.indexedAt.slice(0, 10)}. Do not edit by hand.\n` +
  `window.SHELF = ${JSON.stringify(shelf)};\n`);
console.log(`Wrote ${OUT}: ${shelf.sources.length} sources, ${[...words.values()].reduce((a, b) => a + b, 0)} words.`);
